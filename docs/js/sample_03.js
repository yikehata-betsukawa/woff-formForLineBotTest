/**
* Initialize WOFF
*/
const initializeWoff = (myWoffId) => {
    // init オプションには woffId のみを設定し、自動リダイレクトの衝突を防ぐ
    // woff.init 実行時、SDKが自動的に URL 上の ?code= パラメータを読み取ってセッションを確立します
    woff.init({ woffId: myWoffId })
        .then(() => {
            console.log("WOFF Init 成功");
            initializeApp();
        })
        .catch((err) => {
            console.error("WOFF Init Error:", err);
            document.getElementById("woffInitErrorMessage").hidden = false;
        });
}

const initializeApp = () => {
    displayWoffData();
    registerButtonHandlers();

    if (woff.isLoggedIn()) {
        document.getElementById('woffLoginButton').disabled = true;
        document.getElementById('woffLogoutButton').disabled = false;
    } else {
        document.getElementById('woffLoginButton').disabled = false;
        document.getElementById('woffLogoutButton').disabled = true;
    }
}

// --- 認可コード(code)から ID トークンを安全に取得・デコードする関数 ---
const fetchIdTokenWithCode = async (code) => {
    const clientId = "DICH4bfkjcJBnehVROv9";
    const clientSecret = "Jmup5VMl5K"; // Developer Console の Client Secret
    const redirectUri = "https://stunning-space-enigma-xrx4ww7jppjrhvg7x-9000.app.github.dev/";

    // CORS制約を回避するため corsproxy を利用してトークンエンドポイントへリクエスト
    const targetUrl = 'https://auth.worksmobile.com/oauth2/v2.0/token';
    const proxyUrl = 'https://corsproxy.io/?' + encodeURIComponent(targetUrl);

    const params = new URLSearchParams();
    params.append('grant_type', 'authorization_code');
    params.append('client_id', clientId);
    params.append('client_secret', clientSecret);
    params.append('code', code);
    params.append('redirect_uri', redirectUri);

    try {
        const response = await fetch(proxyUrl, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/x-www-form-urlencoded'
            },
            body: params
        });

        const data = await response.json();
        console.log("Token レスポンスデータ:", data);

        if (data.id_token) {
            // JWT の Payload 部分をデコード
            const base64Url = data.id_token.split('.')[1];
            const base64 = base64Url.replace(/-/g, '+').replace(/_/g, '/');
            const jsonPayload = decodeURIComponent(atob(base64).split('').map(c => {
                return '%' + ('00' + c.charCodeAt(0).toString(16)).slice(-2);
            }).join(''));

            const claims = JSON.parse(jsonPayload);
            console.log("★ 取得成功! ID Token (claims):", claims);
            console.log("ユーザー名 (name):", claims.name);
            console.log("ユーザーID (sub):", claims.sub);
            console.log("ドメインID (domainId):", claims.domainId);

            alert(`IDトークン取得成功！\n\n名前: ${claims.name}\nユーザーID: ${claims.sub}`);
        } else {
            console.error("id_token がレスポンスに含まれていません:", data);
        }
    } catch (err) {
        console.error("トークン交換エラー:", err);
    }
};

// On load
window.addEventListener('load', () => {
    console.log('WOFF_ID: ' + woffId);

    const urlParams = new URLSearchParams(window.location.search);
    const code = urlParams.get('code');

    if (code) {
        console.log("URLから認可コード(code)を検出しました。IDトークンを発行します:", code);
        // code がある場合はプロキシ経由で ID トークンを取得
        fetchIdTokenWithCode(code);
    }

    // 通常通り初期化
    initializeWoff(woffId);
});